/** One key of this plugin's dictionary. */
export type WorktreeCopyKey = keyof typeof zh

/** One listed copy's owning-session facts, as the page and its detail view need them. */
interface OwnerFacts {
  /** Human label the delegation was created with, present for a delegated child. */
  readonly sessionLabel?: string
}

/**
 * The text that names the session a listed copy belongs to.
 *
 * A copy taken by a delegated child says so and names that child; a copy the
 * page's own session took has no chip at all (the caller checks `depth`).
 * @param owner - the listed copy's owning-session facts.
 * @param t - this plugin's locale reader.
 * @returns the localized owner label.
 */
export function subsessionLabel(
  owner: OwnerFacts,
  t: (key: WorktreeCopyKey, params?: Record<string, string>) => string,
): string {
  return owner.sessionLabel === undefined
    ? t('sidebar.subsession')
    : t('sidebar.subsessionNamed', { name: owner.sessionLabel })
}

/**
 * The shared settings form's frame copy, read from this plugin's dictionary.
 * @param t - this plugin's locale reader.
 * @returns the labels the settings form renders.
 */
export function formLabels(t: (key: WorktreeCopyKey) => string) {
  return {
    unavailable: t('settings.unavailable'),
    readOnly: t('settings.readOnly'),
    saveFailed: t('settings.saveFailed'),
  }
}
